#!/usr/bin/env node
// Ports the phrase cards from learn-lang-game (Lexicaster) into snowlearner decks.
//
//   node scripts/port-lexicaster.mjs ../learn-lang-game
//
// Writes decks/<lang>.lexicaster.toml for en and es (pt-BR cues). Words are
// skipped on purpose: snowlearner practices whole sentences you say out loud.
// Re-run after the Lexicaster content changes; never edit the output by hand.

import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const source = resolve(process.argv[2] ?? '../learn-lang-game')
const entry = join(source, 'packages/grimoire/src/content/index.ts')
const out = join(mkdtempSync(join(tmpdir(), 'lexicaster-')), 'content.mjs')
execFileSync('npx', ['--yes', 'esbuild@0.25.10', entry, '--bundle', '--format=esm', '--platform=node', `--outfile=${out}`], {
  stdio: 'inherit',
})
const { PHASES_IN_ORDER, phraseById } = await import(pathToFileURL(out).href)

/** Lexicaster regions are fantasy places; learners pick practical topics. */
const TOPICS = {
  'whispering-woods': 'primeiros contatos',
  'ember-village': 'comida e compras',
  'tidal-library': 'rotina e transporte',
  'obsidian-spire': 'saúde e social',
  'lantern-harbor': 'vida no exterior',
  'guild-hall': 'trabalho',
  hearthstead: 'casa e burocracia',
  'carnival-isles': 'gírias e conversa',
  skyport: 'viagem',
  'feast-hall': 'restaurante',
  'starfall-observatory': 'negociação e opinião',
}

const TARGETS = [
  { lang: 'en', key: 'en-US', name: 'inglês', title: 'Lexicaster: inglês do dia a dia' },
  { lang: 'es', key: 'es', name: 'espanhol', title: 'Lexicaster: espanhol do dia a dia' },
]

// The pixel font covers Latin-1 letters and common punctuation; normalize the rest.
function clean(text) {
  return (text ?? '')
    .replace(/[’‘]/g, "'")
    .replace(/[“”«»]/g, '"')
    .replace(/[–—]/g, '-')
    .replace(/→/g, '->')
    .replace(/\p{Extended_Pictographic}/gu, '')
    .replace(/\s+/g, ' ')
    .trim()
}

const firstSentence = (text) => {
  const t = clean(text)
  const m = t.match(/^.+?[.!?](\s|$)/)
  return (m ? m[0] : t).trim()
}

const str = (s) => JSON.stringify(s)

for (const t of TARGETS) {
  const seen = new Set()
  const lines = [
    '# Generated by scripts/port-lexicaster.mjs from learn-lang-game. Do not edit by hand.',
    `language = ${str(t.lang)}`,
    'native = "pt-BR"',
    `language_name = ${str(t.name)}`,
    `title = ${str(t.title)}`,
    '',
  ]
  let count = 0
  for (const phase of PHASES_IN_ORDER) {
    for (const id of phase.phrases) {
      const p = phraseById(id)
      if (!p) continue
      const say = clean(p.display?.[t.key] ?? p.text[t.key])
      if (!say || seen.has(say.toLowerCase())) continue
      seen.add(say.toLowerCase())
      const accept = [...new Set((p.alt?.[t.key] ?? []).map(clean).filter((a) => a && a.toLowerCase() !== say.toLowerCase()))]
      const tip = clean(p.tips?.[t.key]?.['pt-BR']) || (p.example?.[t.key] ? `Exemplo: ${clean(p.example[t.key])}` : '')
      lines.push('[[phrase]]')
      lines.push(`topic = ${str(TOPICS[phase.regionId] ?? 'geral')}`)
      lines.push(`level = ${str(phase.cefr)}`)
      lines.push(`situation = ${str(firstSentence(p.usage['pt-BR']))}`)
      lines.push(`say = ${str(say)}`)
      lines.push(`meaning = ${str(clean(p.display?.['pt-BR'] ?? p.text['pt-BR']))}`)
      if (accept.length) lines.push(`accept = [${accept.map(str).join(', ')}]`)
      if (tip) lines.push(`tip = ${str(tip)}`)
      lines.push('')
      count++
    }
  }
  const file = resolve(new URL('..', import.meta.url).pathname, 'decks', `${t.lang}.lexicaster.toml`)
  writeFileSync(file, lines.join('\n'))
  console.log(`wrote ${file} (${count} phrases)`)
}
